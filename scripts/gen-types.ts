// Generates src/lib/contract.gen.ts, the TypeScript types for the estate
// report contract, from the vendored JSON Schemas in contract/, and the
// clearcutt-verify release the contract is from (contract/UPSTREAM). Pages
// are typed only by what the contract defines.
//
// Usage: node scripts/gen-types.ts [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { compile, type JSONSchema } from 'json-schema-to-typescript';

const out = new URL('../src/lib/contract.gen.ts', import.meta.url);
const schemas = [
  ['EstateReport', '../contract/estate-report.v1.schema.json'],
  ['EstateHistory', '../contract/estate-history.v1.schema.json'],
] as const;

const banner = `// Generated by scripts/gen-types.ts from contract/*.schema.json. Do not edit;
// run \`npm run gen-types\` after scripts/sync-contract.sh.
/* eslint-disable */
`;

const parts: string[] = [];
for (const [name, file] of schemas) {
  const schema = JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf8')) as JSONSchema;
  const ts = await compile({ ...schema, title: name }, name, {
    bannerComment: '',
    additionalProperties: false,
    unreachableDefinitions: true,
    format: true,
    style: { singleQuote: true },
  });
  parts.push(ts);
}

// The history schema repeats the report's summary definitions. Keep one
// declaration of each name, and stop if the two schemas ever disagree.
const seen = new Map<string, string>();
const normalize = (block: string) => block.replace(/\/\*\*[\s\S]*?\*\/\n/g, '').trim();
const merged = parts
  .join('\n')
  .split(/\n(?=\/\*\*|export )/)
  .reduce<string[]>((out, block) => {
    // Attach each doc comment to the declaration after it.
    if (out.length > 0 && out[out.length - 1].startsWith('/**') && !out[out.length - 1].includes('export ')) {
      out[out.length - 1] += `\n${block}`;
    } else {
      out.push(block);
    }
    return out;
  }, [])
  .filter((block) => {
    const m = block.match(/^export (?:interface|type) (\w+)/m);
    if (!m) return true;
    const body = normalize(block);
    const previous = seen.get(m[1]);
    if (previous === undefined) {
      seen.set(m[1], body);
      return true;
    }
    if (previous !== body) {
      throw new Error(`the report and history schemas define ${m[1]} differently`);
    }
    return false;
  })
  .join('\n');
// Where the contract came from, so a build can say when a report is from a
// newer clearcutt-verify than the one it was built against.
const upstream = readFileSync(new URL('../contract/UPSTREAM', import.meta.url), 'utf8');
const field = (name: string) => upstream.match(new RegExp(`^${name}: (.+)$`, 'm'))?.[1].trim() ?? '';
const release = field('release');
const footer = `
/**
 * The clearcutt-verify commit the vendored contract is from, and the newest
 * release at or before it ("none" when there is none), from contract/UPSTREAM.
 */
export const CONTRACT_UPSTREAM = {
  commit: ${JSON.stringify(field('commit'))},
  release: ${JSON.stringify(/^v\d+\.\d+\.\d+$/.test(release) ? release : 'none')},
} as const;
`;
const text = banner + merged.trim() + '\n' + footer;

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error('src/lib/contract.gen.ts is out of date; run npm run gen-types');
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
